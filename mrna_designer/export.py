"""Exporters: RNA FASTA, CDS FASTA, protein FASTA, annotated GenBank,
JSON design manifest, and a human-readable report.

Honesty rules enforced here:
  * No transcription promoter in the mature-RNA export.
  * Cap chemistry and modified nucleosides appear only as annotations/metadata,
    never as letters in the sequence.
  * poly(A): the exported length matches the declared mode (encoded letters are
    present only when mode == 'encoded'; otherwise it is a note).
  * RNA vs DNA representation is explicit and labeled.
  * GenBank is produced with BioPython (a real writer); an optional IVT DNA
    template export is separately labeled. We do NOT rename another format with
    a MacVector extension — GenBank is emitted as standard .gb and documented as
    MacVector-importable.
  * Every export round-trips through a parser (sequence identity + feature
    coordinates) and that check is reported.
"""
from __future__ import annotations

import io
import json
from datetime import date

from Bio import SeqIO
from Bio.Seq import Seq
from Bio.SeqFeature import FeatureLocation, SeqFeature
from Bio.SeqRecord import SeqRecord

from .assemble import AssemblyResult
from .genetic_code import normalize_dna
from .schemas import Design


def _wrap_fasta(header: str, seq: str, width: int = 70) -> str:
    lines = [f">{header}"]
    for i in range(0, len(seq), width):
        lines.append(seq[i : i + width])
    return "\n".join(lines) + "\n"


def protein_fasta(design: Design) -> str:
    prot = design.transcript.intended_protein if design.transcript else design.architecture.assembled_protein()
    return _wrap_fasta(f"{design.design_id}|protein|{len(prot)}aa|intended", prot)


def cds_fasta(design: Design) -> str:
    if not design.transcript:
        raise ValueError("no transcript to export")
    cds = design.transcript.optimized_cds
    return _wrap_fasta(
        f"{design.design_id}|CDS|RNA|{len(cds)}nt|includes_stop=yes", cds
    )


def rna_fasta(design: Design) -> str:
    if not design.transcript:
        raise ValueError("no transcript to export")
    rna = design.transcript.mature_rna()
    polyA = design.transcript.polyA
    tail = (f"polyA_encoded={polyA.length}" if polyA.mode == "encoded"
            else f"polyA_post_transcriptional_intended={polyA.length}")
    header = (f"{design.design_id}|mature_mRNA|RNA|{len(rna)}nt|"
              f"no_promoter|cap={design.transcript.cap.name}(metadata)|{tail}")
    return _wrap_fasta(header, rna)


def _genbank_record(design: Design, as_dna_template: bool = False) -> SeqRecord:
    """Build an annotated GenBank record for the mature mRNA (RNA) or, when
    as_dna_template=True, a separately-labeled IVT DNA template (T->... stays DNA).
    No promoter is added in either case here; a promoter, if ever added, would be
    an explicit, separately-validated feature."""
    t = design.transcript
    assert t is not None
    rna = t.mature_rna()  # A/C/G/U
    if as_dna_template:
        seq_str = rna.replace("U", "T")
        mol_type = "DNA"
        name = f"{design.design_id}_ivt_template"
    else:
        # GenBank sequences are stored as DNA letters by convention; we keep the
        # RNA identity explicit via molecule_type=mRNA and a note.
        seq_str = rna.replace("U", "T")
        mol_type = "mRNA"
        name = f"{design.design_id}_mRNA"

    rec = SeqRecord(Seq(seq_str), id=design.design_id, name=name[:16],
                    description=design.architecture.title[:150])
    rec.annotations["molecule_type"] = mol_type
    rec.annotations["topology"] = "linear"
    rec.annotations["date"] = date.today().strftime("%d-%b-%Y").upper()
    rec.annotations["data_file_division"] = "SYN"
    rec.annotations["organism"] = "synthetic construct"
    rec.annotations["comment"] = (
        f"Generated by mRNA Designer. design_id={design.design_id}. "
        f"RNA representation (U) shown here as DNA letters (T) for GenBank; "
        f"molecule_type={mol_type}. No transcription promoter is included. "
        f"Cap={t.cap.name} ({t.cap.chemistry}) is METADATA ONLY and is not in the sequence. "
        + (f"Modified nucleosides (metadata only): "
           + "; ".join(f"{m.name} replaces {m.replaces}" for m in t.mod_nucleosides) + ". "
           if t.mod_nucleosides else "")
        + ("poly(A) is ENCODED in the sequence. " if t.polyA.mode == "encoded"
           else f"poly(A) is POST-TRANSCRIPTIONAL (intended length {t.polyA.length}); NOT in the exported sequence. ")
        + ("THIS RECORD IS A SYNTHETIC DEMO FIXTURE. " if design.is_demo_fixture else "")
    )

    # ---- transcript element features (coordinates are 0-based half-open) --
    pos = 0

    def add(feat_type: str, length: int, qualifiers: dict):
        nonlocal pos
        if length <= 0:
            return
        rec.features.append(SeqFeature(
            FeatureLocation(pos, pos + length), type=feat_type, qualifiers=qualifiers
        ))
        pos += length

    if t.five_utr:
        add("5'UTR", len(normalize_dna(t.five_utr.sequence)),
            {"label": [t.five_utr.name], "note": [f"source={t.five_utr.source_id}; {t.five_utr.uncertainty}"]})
    if t.kozak:
        add("regulatory", len(normalize_dna(t.kozak.sequence)),
            {"regulatory_class": ["other"], "label": ["Kozak"],
             "note": [f"source={t.kozak.source_id}"]})
    cds_len = len(normalize_dna(t.optimized_cds))
    # CDS feature + protein translation + component sub-features
    cds_start = pos
    rec.features.append(SeqFeature(
        FeatureLocation(cds_start, cds_start + cds_len), type="CDS",
        qualifiers={
            "label": [design.architecture.title[:60] or "CDS"],
            "translation": [t.intended_protein],
            "note": ["optimized CDS including stop codon"],
            "codon_start": [1],
        },
    ))
    # protein-feature sub-annotations mapped from assembly spans (aa -> nt)
    asm = _assembly_of(design)
    if asm is not None:
        for s in asm.spans:
            if s.end_aa < s.start_aa:
                continue
            nt_start = cds_start + (s.start_aa - 1) * 3
            nt_end = cds_start + s.end_aa * 3
            rec.features.append(SeqFeature(
                FeatureLocation(nt_start, nt_end),
                type={"signal_peptide": "sig_peptide"}.get(s.kind, "misc_feature"),
                qualifiers={"label": [s.name], "note": [f"{s.kind}; provenance={s.provenance}"]},
            ))
    pos = cds_start + cds_len

    if t.three_utr:
        add("3'UTR", len(normalize_dna(t.three_utr.sequence)),
            {"label": [t.three_utr.name], "note": [f"source={t.three_utr.source_id}; {t.three_utr.uncertainty}"]})
    if t.polyA.mode == "encoded" and t.polyA.length > 0:
        add("polyA_signal", t.polyA.length,
            {"label": [f"encoded poly(A) n={t.polyA.length}"], "note": ["encoded tail"]})
    return rec


def _assembly_of(design: Design) -> AssemblyResult | None:
    try:
        from .assemble import assemble

        return assemble(design.architecture)
    except Exception:
        return None


def genbank(design: Design, as_dna_template: bool = False) -> str:
    rec = _genbank_record(design, as_dna_template=as_dna_template)
    buf = io.StringIO()
    SeqIO.write(rec, buf, "genbank")
    return buf.getvalue()


def design_manifest(design: Design) -> str:
    """JSON manifest: the full design object (typed) with provenance intact."""
    return json.dumps(json.loads(design.model_dump_json()), indent=2, default=str)


def roundtrip_check(design: Design) -> dict:
    """Write GenBank, re-parse it, verify sequence identity and feature coords.
    Returns a dict describing the check (never silently passes)."""
    result = {"genbank_roundtrip": "unevaluated", "fasta_roundtrip": "unevaluated",
              "detail": ""}
    if not design.transcript:
        result["detail"] = "no transcript"
        return result
    # GenBank round-trip
    gb = genbank(design)
    rec = next(SeqIO.parse(io.StringIO(gb), "genbank"))
    expected_dna = design.transcript.mature_rna().replace("U", "T")
    seq_ok = str(rec.seq).upper() == expected_dna.upper()
    n_feats = len(rec.features)
    # check CDS feature coordinates match CDS length
    cds_feats = [f for f in rec.features if f.type == "CDS"]
    cds_ok = bool(cds_feats) and (
        len(cds_feats[0]) == len(normalize_dna(design.transcript.optimized_cds))
    )
    result["genbank_roundtrip"] = "pass" if (seq_ok and cds_ok) else "fail"
    # FASTA round-trip (RNA)
    fa = rna_fasta(design)
    frec = next(SeqIO.parse(io.StringIO(fa), "fasta"))
    fasta_ok = str(frec.seq).upper() == design.transcript.mature_rna().upper()
    result["fasta_roundtrip"] = "pass" if fasta_ok else "fail"
    result["detail"] = (
        f"genbank: seq_identity={'ok' if seq_ok else 'MISMATCH'}, "
        f"cds_coords={'ok' if cds_ok else 'MISMATCH'}, features={n_feats}; "
        f"fasta: seq_identity={'ok' if fasta_ok else 'MISMATCH'}"
    )
    return result


def report_text(design: Design) -> str:
    """Human-readable research + validation report."""
    L: list[str] = []
    A = L.append
    A("=" * 72)
    A(f"mRNA DESIGNER — DESIGN REPORT   {design.design_id}")
    A("=" * 72)
    if design.is_demo_fixture:
        A("*** DEMO FIXTURE: uses bundled synthetic data, NOT live research ***")
    A(f"Created: {design.created}")
    A(f"Title:   {design.architecture.title}")
    A(f"Status:  {design.status.value}")
    A("")
    A("-- REQUEST ------------------------------------------------------------")
    A(f"text:        {design.request.text!r}")
    A(f"identifier:  {design.request.protein_identifier!r}")
    ctx = design.request.context
    A(f"protein species (encoded): {ctx.protein_species!r}")
    A(f"expression host:           {ctx.expression_host!r}  (independent of above)")
    A(f"cell type / in-vivo:       {ctx.cell_type!r} / {ctx.in_vivo!r}")
    A("")
    A("-- ARCHITECTURE -------------------------------------------------------")
    order = design.architecture.fusion_order or list(range(len(design.architecture.components)))
    for rank, idx in enumerate(order, 1):
        c = design.architecture.components[idx]
        state = "resolved" if c.resolved else "UNRESOLVED"
        A(f"  {rank}. [{c.kind}] {c.name}  ({state}, provenance={c.provenance.value})")
        if c.accession:
            A(f"       accession={c.accession} ver={c.accession_version}")
        if c.sequence:
            A(f"       {len(c.sequence)} aa: {c.sequence[:48]}{'…' if len(c.sequence) > 48 else ''}")
        if c.note:
            A(f"       note: {c.note}")
    if design.architecture.assumptions:
        A("  Assumptions:")
        for a in design.architecture.assumptions:
            A(f"    - {a.field} = {a.value}  ({a.rationale})")
    if design.architecture.unresolved:
        A("  UNRESOLVED dependencies:")
        for u in design.architecture.unresolved:
            A(f"    - {u}")
    A("")
    A("-- EVIDENCE -----------------------------------------------------------")
    if not design.evidence:
        A("  (no evidence records attached)")
    for e in design.evidence:
        A(f"  [{e.match_quality}] {e.title}")
        A(f"       url={e.url}  doi={e.doi}  pmid={e.pmid}  acc={e.accession}")
        A(f"       retrieved={e.retrieved}  provenance={e.provenance.value}")
        A(f"       finding: {e.finding}")
        A(f"       experimental context: {e.experimental_context}")
        A(f"       exact sequence available: {e.exact_sequence_available}")
        if e.supports_decision:
            A(f"       supports: {e.supports_decision}")
    A("  Retrieval states:")
    for rs in design.retrieval_states:
        A(f"    - {rs.integration}: attempted={rs.attempted} live={rs.live} ok={rs.ok} :: {rs.detail}")
    A("")
    if design.optimization:
        o = design.optimization
        A("-- OPTIMIZATION -------------------------------------------------------")
        A(f"  optimizer={o.optimizer_version}  codon_table={o.codon_table_version}  seed={o.seed}")
        A(f"  host={o.objectives.host}  GC target=[{o.objectives.target_gc_min},{o.objectives.target_gc_max}]"
          f"  max_homopolymer={o.objectives.max_homopolymer}")
        A(f"  forbidden_motifs={o.objectives.forbidden_motifs}")
        A("  candidates (lower penalty is better):")
        for c in o.candidates:
            star = " *SELECTED*" if c.candidate_id == o.selected_id else (" (baseline)" if c.is_baseline else "")
            m = c.metrics
            A(f"    {c.candidate_id:20s} penalty={c.objective_score:<7} CAI={m.cai:<6} "
              f"GC={m.gc_content:<6} hp={m.max_homopolymer} localGC=[{m.min_local_gc},{m.max_local_gc}]"
              f" motif={m.forbidden_motif_hits}{star}")
        A(f"  rationale: {o.selection_rationale}")
        A("")
    if design.validation:
        v = design.validation
        A("-- VALIDATION ---------------------------------------------------------")
        A(f"  ERRORS ({len(v.errors)}):")
        for i in v.errors:
            A(f"    [ERROR] {i.check}: {i.message}")
        A(f"  WARNINGS ({len(v.warnings)}):")
        for i in v.warnings:
            A(f"    [warn]  {i.check}: {i.message}")
        A(f"  UNEVALUATED ({len(v.unevaluated)}):")
        for i in v.unevaluated:
            A(f"    [n/e]   {i.check}: {i.message}")
        if v.size:
            s = v.size
            A("  SIZE:")
            A(f"    protein={s.protein_len_aa} aa; CDS={s.cds_len_nt} nt (includes_stop={s.cds_includes_stop})")
            A(f"    5'UTR={s.five_utr_len_nt}  3'UTR={s.three_utr_len_nt}  "
              f"polyA({s.polyA_mode})={s.polyA_encoded_len_nt}  TOTAL_RNA={s.total_rna_len_nt} nt")
            A(f"    software_input_limit={s.software_input_limit_nt} nt (NOT a biological recommendation)")
            A(f"    biological guidance: {s.biological_guidance} "
              f"[source={s.guidance_source_id}, uncertain={s.guidance_is_uncertain}]")
        A("")
    A("-- SEQUENCES ----------------------------------------------------------")
    if design.transcript:
        A(f"  intended protein ({len(design.transcript.intended_protein)} aa):")
        A(f"    {design.transcript.intended_protein}")
        A(f"  optimized CDS (RNA, {len(design.transcript.optimized_cds)} nt, incl. stop):")
        A(f"    {design.transcript.optimized_cds}")
        A(f"  mature mRNA (RNA, {len(design.transcript.mature_rna())} nt, no promoter, cap=metadata):")
        rna = design.transcript.mature_rna()
        A(f"    {rna[:120]}{'…' if len(rna) > 120 else ''}")
    A("")
    A("NOTE: All results above are COMPUTATIONAL. They are not experimental")
    A("evidence of expression, secretion, activity, stability, or delivery.")
    A("=" * 72)
    return "\n".join(L) + "\n"
